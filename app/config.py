"""Настройки сборки расписания УМПК."""
from __future__ import annotations

import os
from datetime import date
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
# Папка называется docs, потому что GitHub Pages умеет раздавать сайт только
# из корня репозитория или из /docs. Внутри — обычные файлы сайта.
WEB_DIR = BASE_DIR / "docs"
SITE_DATA_FILE = WEB_DIR / "data" / "schedule.json"   # то, что читает сайт
DATA_DIR = BASE_DIR / "data"
RAW_DIR = DATA_DIR / "raw"          # последние скачанные .xlsx, в репозиторий не идут

# Публичная папка облака Mail.ru со всеми файлами расписания.
# Тот же адрес зашит в кнопку «Таблицы в облаке» в подвале docs/index.html —
# меняете папку, поправьте оба места.
CLOUD_PUBLIC_LINK = os.getenv("UMPK_CLOUD_LINK", "KRh4/Q5UoGDxkv")
HTTP_TIMEOUT = int(os.getenv("UMPK_HTTP_TIMEOUT", "60"))

# Понедельник, от которого считается чётность недель, если в таблицах
# не нашлось ни одной даты.
DEFAULT_ANCHOR = date(2026, 8, 31)

# Название учебного заведения (выводится в шапке сайта).
COLLEGE_SHORT = "УМПК"
COLLEGE_FULL = "Уфимский многопрофильный профессиональный колледж"

# Ручные исправления опечаток в названиях групп.
# Ключ — как разбор назвал повторяющийся столбец, значение — как правильно.
# В «ДИ ТИК ПК.xlsx» две разные группы подписаны «3 ТИК А»; вторая из них —
# на самом деле «3 ТИК Б». Когда опечатку поправят в самой таблице, строку
# отсюда можно убрать: разбор перестанет находить дубль и правило не сработает.
GROUP_RENAMES = {
    "3 ТИК А (2)": "3 ТИК Б",
}

# Какой лист брать, если в книге несколько листов на одну и ту же неделю.
# Так бывает, когда в Excel продублировали вкладку: рядом с «2 неделя»
# появляется «2 неделя (2)». Складывать их нельзя — все пары удвоятся,
# поэтому берём ровно один, а про остальные пишем предупреждение.
#   "first" — первый, с исходным именем листа
#   "last"  — последний по порядку, то есть копия
# Берём первый: копию в колледже завели и забыли, правки идут в оригинал.
# Видно по аудиториям — 178 пар, где в оригинале аудитория проставлена,
# а в копии пусто; обратных случаев нет ни одного.
SHEET_PREFERENCE = "first"

# Колледж занимает два корпуса, и номера кабинетов в них совпадают: «204»
# в первом и «204» во втором — разные комнаты. В таблицах корпус отдельно
# не указан, он понятен по специальности группы. Исключение — когда группа
# идёт в чужое здание: тогда в клетке пишут «2 корпус» или «2 кор. 110»,
# и такая пометка сильнее принадлежности группы.
#
# Оба списка заданы явно нарочно. Появится новая специальность — сборка
# не станет молча приписывать её ко второму корпусу, а напишет предупреждение
# на странице «О расписании».
# Разнобой в написании одного и того же помещения. Для показа расписания он
# безобиден, а в списке аудиторий даёт две строки вместо одной.
# Залы в корпусах разные, поэтому они всё равно остаются отдельными —
# выправляется только написание.
ROOM_RENAMES = {
    "актзал": "акт. зал",
}

FIRST_BUILDING_SPECS = {"ФК", "АФК", "ДИ", "П", "ПК", "ТИК"}
SECOND_BUILDING_SPECS = {"БД", "ДОШ", "ИСиП", "НАЧ", "ОИБАС", "ОИСиР", "РУПО", "ЭкБ"}
UNKNOWN_SPEC_BUILDING = 2          # куда относить специальность не из списков

RAW_DIR.mkdir(parents=True, exist_ok=True)
